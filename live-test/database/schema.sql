  KEY idx_questions_test_id (test_id),
  KEY idx_questions_section_id (section_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE test_attempts (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  test_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  registration_id BIGINT UNSIGNED NOT NULL,
  started_at DATETIME NULL,
  submitted_at DATETIME NULL,
  status ENUM('not_started', 'in_progress', 'submitted', 'auto_submitted') NOT NULL DEFAULT 'not_started',
  violation_count INT UNSIGNED NOT NULL DEFAULT 0,
  eligibility_status ENUM('clean', 'warning', 'suspicious', 'disqualified') NOT NULL DEFAULT 'clean',
  leaderboard_eligible TINYINT(1) NOT NULL DEFAULT 1,
  prize_eligible TINYINT(1) NOT NULL DEFAULT 1,
  disqualification_reason TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_attempts_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
  CONSTRAINT fk_attempts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_attempts_registration FOREIGN KEY (registration_id) REFERENCES test_registrations(id) ON DELETE CASCADE,
  UNIQUE KEY uq_attempts_registration (registration_id),
  KEY idx_attempts_test_id (test_id),
  KEY idx_attempts_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE user_answers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  attempt_id BIGINT UNSIGNED NOT NULL,
  question_id BIGINT UNSIGNED NOT NULL,
  selected_option ENUM('A', 'B', 'C', 'D') NULL,
  answer_status ENUM('not_visited', 'answered', 'not_answered', 'marked_review', 'answered_marked_review') NOT NULL DEFAULT 'not_visited',
  time_spent_seconds INT UNSIGNED NOT NULL DEFAULT 0,
  change_count INT UNSIGNED NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_answers_attempt FOREIGN KEY (attempt_id) REFERENCES test_attempts(id) ON DELETE CASCADE,
  CONSTRAINT fk_user_answers_question FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE,
  UNIQUE KEY uq_user_answers_attempt_question (attempt_id, question_id),
  KEY idx_user_answers_attempt_id (attempt_id),
  KEY idx_user_answers_question_id (question_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE violation_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  attempt_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NULL,
  test_id BIGINT UNSIGNED NULL,
  registration_id BIGINT UNSIGNED NULL,
  violation_type VARCHAR(80) NOT NULL,
  event_source VARCHAR(80) NULL,
  event_label VARCHAR(160) NULL,
  client_timestamp VARCHAR(80) NULL,
