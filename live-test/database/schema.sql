CREATE TABLE admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('super_admin', 'admin') NOT NULL DEFAULT 'admin',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  last_login_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_admins_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  mobile VARCHAR(20) NOT NULL,
  email VARCHAR(190) NULL,
  category VARCHAR(60) NULL,
  city VARCHAR(120) NULL,
  state VARCHAR(120) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_users_mobile (mobile),
  UNIQUE KEY uq_users_email (email),
  KEY idx_users_mobile (mobile)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tests (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(220) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  test_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  duration_minutes INT UNSIGNED NOT NULL DEFAULT 60,
  registration_start_at DATETIME NULL,
  registration_end_at DATETIME NULL,
  registration_limit INT UNSIGNED NOT NULL DEFAULT 300,
  status ENUM('upcoming', 'registration_open', 'live', 'closed', 'result_published', 'archived') NOT NULL DEFAULT 'upcoming',
  is_free TINYINT(1) NOT NULL DEFAULT 1,
  fee_amount_paise INT NOT NULL DEFAULT 500,
  result_visible TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_tests_slug (slug),
  KEY idx_tests_status (status),
  KEY idx_tests_date_status (test_date, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE test_sections (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  test_id BIGINT UNSIGNED NOT NULL,
  section_name VARCHAR(120) NOT NULL,
  section_slug VARCHAR(140) NOT NULL,
  section_order INT UNSIGNED NOT NULL,
  question_count INT UNSIGNED NOT NULL DEFAULT 20,
  duration_minutes INT UNSIGNED NOT NULL,
  is_locked_after_time TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_test_sections_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
  UNIQUE KEY uq_test_sections_slug (test_id, section_slug),
  UNIQUE KEY uq_test_sections_order (test_id, section_order),
  KEY idx_test_sections_test_id (test_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE test_registrations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  test_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  registration_id VARCHAR(40) NOT NULL,
  registered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status ENUM('registered', 'cancelled') NOT NULL DEFAULT 'registered',
  payment_status VARCHAR(30) NOT NULL DEFAULT 'not_required',
  amount_paise INT NOT NULL DEFAULT 0,
  discount_paise INT NOT NULL DEFAULT 0,
  payable_paise INT NOT NULL DEFAULT 0,
  promo_code_id INT UNSIGNED NULL,
  payment_id BIGINT UNSIGNED NULL,
  payment_verified_at DATETIME NULL,
  source VARCHAR(50) NOT NULL DEFAULT 'website',
  CONSTRAINT fk_registrations_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
  CONSTRAINT fk_registrations_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  UNIQUE KEY uq_registrations_registration_id (registration_id),
  UNIQUE KEY uq_registrations_test_user (test_id, user_id),
  KEY idx_registrations_test_id (test_id),
  KEY idx_registrations_user_id (user_id),
  KEY idx_registrations_payment_status (test_id, payment_status),
  KEY idx_registrations_promo_code_id (promo_code_id),
  KEY idx_registrations_payment_id (payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE questions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  test_id BIGINT UNSIGNED NOT NULL,
  section_id BIGINT UNSIGNED NOT NULL,
  question_number INT UNSIGNED NOT NULL,
  question_hi TEXT NULL,
  question_en TEXT NULL,
  question_image_path VARCHAR(255) NULL,
  question_image_alt VARCHAR(255) NULL,
  option_a_hi TEXT NULL,
  option_b_hi TEXT NULL,
  option_c_hi TEXT NULL,
  option_d_hi TEXT NULL,
  option_a_en TEXT NULL,
  option_b_en TEXT NULL,
  option_c_en TEXT NULL,
  option_d_en TEXT NULL,
  option_a_image_path VARCHAR(255) NULL,
  option_b_image_path VARCHAR(255) NULL,
  option_c_image_path VARCHAR(255) NULL,
  option_d_image_path VARCHAR(255) NULL,
  correct_option ENUM('A', 'B', 'C', 'D') NOT NULL,
  explanation_hi TEXT NULL,
  explanation_en TEXT NULL,
  explanation_image_path VARCHAR(255) NULL,
  difficulty_level ENUM('easy', 'medium', 'hard') NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
